        static final String API = "https://api.opendex.lemoncore.io";
        static final HttpClient HTTP = HttpClient.newHttpClient();
        static final Pattern MACHINE = Pattern.compile("(tm|hm|tr)(\\d+)");

        private static Map<String, Object> index;
        private static Path folder;

        static String dataVersion() { return (String) index.get("dataVersion"); }

