    /**
     * Reads openDex's bulk game data and presents each resource as the flat tables the generator reads (named as PokéAPI's
     * CSVs were). Documents link to each other by name and URL, so ids are taken from the end of the URL; booleans become
     * 1 and 0 and nulls empty cells, as in the CSVs. Where openDex's documents differ from the tables, the difference is
     * handled in the one place below and says so.
     */
