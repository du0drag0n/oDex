    // ---- minimal JSON reader ---------------------------------------------------------------------------------------------------

    /** Parses JSON into maps, lists, strings, longs, doubles, booleans and null. */
    static final class JsonReader {
        private final String s;
        private int p;

        JsonReader(String s) { this.s = s; }

        Object read() {
            Object v = value();
            ws();
            if (p != s.length()) throw new IllegalStateException("trailing JSON at " + p);
            return v;
        }

        private void ws() { while (p < s.length() && s.charAt(p) <= ' ') p++; }

        private Object value() {
            ws();
            char c = s.charAt(p);
            switch (c) {
                case '{': {
                    p++;
                    Map<String, Object> m = new LinkedHashMap<>();
                    ws();
                    if (s.charAt(p) == '}') { p++; return m; }
                    while (true) {
                        ws();
                        String k = string();
                        ws();
                        p++; // ':'
                        m.put(k, value());
                        ws();
                        if (s.charAt(p++) == '}') return m;
                    }
                }
                case '[': {
                    p++;
                    List<Object> l = new ArrayList<>();
                    ws();
                    if (s.charAt(p) == ']') { p++; return l; }
                    while (true) {
                        l.add(value());
                        ws();
                        if (s.charAt(p++) == ']') return l;
                    }
                }
                case '"': return string();
                case 't': p += 4; return Boolean.TRUE;
                case 'f': p += 5; return Boolean.FALSE;
                case 'n': p += 4; return null;
                default: {
                    int start = p;
                    while (p < s.length() && "+-0123456789.eE".indexOf(s.charAt(p)) >= 0) p++;
                    String n = s.substring(start, p);
                    return n.indexOf('.') >= 0 || n.indexOf('e') >= 0 || n.indexOf('E') >= 0 ? (Object) Double.valueOf(n) : (Object) Long.valueOf(n);
                }
            }
        }

        private String string() {
            p++; // opening quote
            int start = p;
            while (s.charAt(p) != '"' && s.charAt(p) != '\\') p++;
            if (s.charAt(p) == '"') return s.substring(start, p++);
            StringBuilder b = new StringBuilder(s.substring(start, p));
            while (true) {
                char c = s.charAt(p++);
                if (c == '"') return b.toString();
                if (c != '\\') { b.append(c); continue; }
                char e = s.charAt(p++);
                switch (e) {
                    case 'n' -> b.append('\n');
                    case 't' -> b.append('\t');
                    case 'r' -> b.append('\r');
                    case 'b' -> b.append('\b');
                    case 'f' -> b.append('\f');
                    case 'u' -> { b.append((char) Integer.parseInt(s.substring(p, p + 4), 16)); p += 4; }
                    default -> b.append(e); // " \ /
                }
            }
        }
    }

    // ---- minimal JSON writer ---------------------------------------------------------------------------------------------------

    static final class Json {
        private final StringBuilder b = new StringBuilder();
        private final Deque<Boolean> first = new ArrayDeque<>();
        private boolean afterKey = false;

        private void sep() {
            if (afterKey) { afterKey = false; return; }
            if (!first.isEmpty()) {
                if (first.peek()) { first.pop(); first.push(false); } else b.append(',');
            }
        }
        Json beginObject() { sep(); b.append('{'); first.push(true); return this; }
        Json endObject() { first.pop(); b.append('}'); return this; }
        Json beginArray() { sep(); b.append('['); first.push(true); return this; }
        Json endArray() { first.pop(); b.append(']'); return this; }
        Json key(String k) { sep(); str(k); b.append(':'); afterKey = true; return this; }
        Json value(int v) { sep(); b.append(v); return this; }
        Json value(Integer v) { sep(); b.append(v == null ? "null" : v.toString()); return this; }
        Json value(boolean v) { sep(); b.append(v); return this; }
        Json value(String v) { sep(); if (v == null) b.append("null"); else str(v); return this; }
        private void str(String s) {
            b.append('"');
            for (int i = 0; i < s.length(); i++) {
                char c = s.charAt(i);
                switch (c) {
                    case '"' -> b.append("\\\"");
                    case '\\' -> b.append("\\\\");
                    case '\n' -> b.append("\\n");
                    case '\r' -> b.append("\\r");
                    case '\t' -> b.append("\\t");
                    default -> { if (c < 0x20) b.append(String.format("\\u%04x", (int) c)); else b.append(c); }
                }
            }
            b.append('"');
        }
        int length() { return b.length(); }
        @Override public String toString() { return b.toString(); }
    }
